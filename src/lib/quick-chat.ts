/**
 * 短い日常会話かどうかの判定（ローカル AI で答えてよいか）。安全側に倒す：
 *   - あいさつ・お礼・相づち・気分のひとことのような「決まった形の短い発言」だけをローカル AI にする
 *   - 予定・ToDo・記憶・検索・メール・音楽・資料・会社・授業などツールや情報が要りそうな言葉が入っていたら、いつもどおり Gemini（FRIDAY Core）
 *   - 直前に FRIDAY が質問していたら（「追加しますか？」への「はい」など）、答えが操作につながるので Gemini
 *   - 写真・ファイル・録った声が付いていたら Gemini
 *   - 迷ったら Gemini
 * 依存なし（テストでそのまま読める）。
 */

export interface QuickChatInput {
  /** いまの発言 */
  text: string;
  /** 直前の FRIDAY の返事 */
  previousAssistant?: string;
  /** 写真・ファイル・録った声が付いているか */
  hasAttachment?: boolean;
}

/** これより長い発言は「短い日常会話」とみなさない */
export const QUICK_MAX_CHARS = 24;

/** ローカル AI で答えてよい決まった形（発言の頭から） */
const CASUAL =
  /^(やあ|よう|ハロー|はろー|hello|hi|hey|こんにちは|こんちは|こんばんは|おつかれ|お疲れ|ただいま|おかえり|いってきます|行ってきます|いってらっしゃい|ありがとう|ありがと|あざす|サンキュー|thanks|thank you|どうも|了解|りょうかい|おけ|ok|オッケー|おっけー|うん|はい|いいえ|ううん|なるほど|そっか|そうか|そうなんだ|そうだね|いいね|すごい|すげー|最高|やった|よし|ナイス|さすが|へー|へえ|ふーん|笑|w+$|元気|調子どう|調子は|眠い|ねむい|疲れた|つかれた|暇|ひま|お腹すいた|おなかすいた|腹減った|寒い|さむい|暑い|あつい|がんば|頑張|おやすみ|よろしく|ごめん|すまん|好き|かわいい|かっこいい|面白い|おもしろい|楽しい|たのしい|嬉しい|うれしい|雑談|話そう|話し相手)/i;

/** ツール・情報が要りそうな言葉（1 つでも入っていたら Gemini） */
const NEEDS_CORE =
  /予定|スケジュール|カレンダー|todo|タスク|やること|覚え|記憶|忘れ|リマインド|知らせ|通知|アラーム|タイマー|集中|ポモドーロ|開いて|開け|閉じ|調べ|検索|ググ|ニュース|天気|雨|気温|メール|返信|下書き|音楽|曲|流して|かけて|再生|止めて|とめて|次の|音量|資料|pdf|スライド|文書|書いて|まとめ|要約|翻訳|計算|会社|arqo|アルコ|re-?palette|リパレット|青学|授業|講義|課題|テスト|試験|クイズ|ホログラム|写真|カメラ|画面|api|残り|使用量|振り返り|日記|進捗|プロジェクト|教えて|して(くれ|ほしい|ください|よ$)|やって|作って|送って|入れて|追加|消して|削除|変更|登録|予約|いつ|どこ|だれ|誰|何時|何日|何曜|なんで|なぜ|どうして|どうやって|どうすれば|どうしたら|何を|なに|何が|いくら|どれ|おすすめ|比べ|違い|意味|とは|今日|明日|明後日|昨日|今週|来週|先週|今月|来月|月曜|火曜|水曜|木曜|金曜|土曜|日曜|午前|午後|朝に|夜に|時に|お願い|頼む|頼んだ|じゃあ|では|それで|あと|ついでに|https?:|www\.|\d/i;

/** 決まった形のあとに続いてよいのは、語尾や記号だけ（「なるほどね」「疲れた〜」「元気？」） */
const MAX_TAIL = 6;

/** 直前の FRIDAY の返事が質問で終わっているか（答えが操作につながるかもしれない） */
const ASKED = /(\?|？|ますか|ですか|でしょうか|しますか|しましょうか|いかがですか|どうしますか)[」』)）\s]*$/;

/** 短い日常会話か（ローカル AI で答えてよいか） */
export function isQuickChat({ text, previousAssistant, hasAttachment }: QuickChatInput): boolean {
  const t = text.trim().replace(/^(フライデー|ふらいでー|friday)[、,\s]*/i, "");
  if (!t || hasAttachment) return false;
  if (t.length > QUICK_MAX_CHARS) return false;
  if (t.includes("\n")) return false;
  if (previousAssistant && ASKED.test(previousAssistant.trim().slice(-40))) return false;
  if (NEEDS_CORE.test(t)) return false;
  const m = CASUAL.exec(t);
  if (!m) return false;
  // 決まった形のあとに別の用件が続いていたら（「了解です。では…」）Gemini
  const tail = t.slice(m[0].length).replace(/[！!。．.、,〜~ー…ｗw\s?？♪☺️😊]/g, "");
  return tail.length <= MAX_TAIL;
}
