/**
 * 朝のブリーフィング（「おはよう」「今日のことまとめて」）。
 * 予定・天気・ToDo・メールは普段の材料をそのまま使い、最近の授業の復習ポイントを足して、30 秒ほどで話す。
 */
import type { LectureDigest } from "@/integrations/brain-notes";

/** 朝のあいさつ・今日のまとめを頼まれたか */
export function asksForMorning(text: string): boolean {
  const t = text.trim().replace(/^(フライデー|friday)[、,\s]*/i, "");
  return /^(おはよう|おはよ|おっはよ|グッドモーニング|good\s*morning)/i.test(t) || /ブリーフィング|今日の(予定|こと|一日)を?(まとめて|教えて|確認)|今日(は)?何がある/.test(t);
}

export function morningSection(m: { lectures: LectureDigest[] }, voice: boolean): string {
  const lectures = m.lectures.length
    ? m.lectures
        .map((l) => `## ${l.date} ${l.subject}「${l.title}」\n### 重要なところ\n${l.key || "（なし）"}\n### 復習チェック\n${l.review || "（なし）"}\n### 課題・連絡\n${l.tasks || "（なし）"}`)
        .join("\n\n")
    : "（最近の授業ノートはない）";
  return `

# 朝のブリーフィング（今回はこれをする）
- 副社長兼秘書として、今日の状況を落ち着いて手短に伝える。${voice ? "声で読み上げるので、全体で 30 秒ほど（6〜9 文）の話し言葉で。見出し・箇条書き・記号は使わない。" : "短い見出しと箇条書きで、30 秒で読める量に。"}
- 順番：短いあいさつ（「おはようございます」。時間帯に合わせる）→ 今日の予定（時刻順。最初の予定まであとどれくらいか）→ 天気（気温・傘が要るか）→ 今日・明日が期限の ToDo と、期限を過ぎたもの → 止まっているプロジェクト（プロジェクト一覧で［止まっている］のもの）があれば一番長いものを一言と次の一手 → 最近の授業の復習ポイントを 1〜2 個（問いの形で軽く）→ 未読メールで大事そうなものがあれば一言 → 最後に、今日いちばん優先すべきことを一つ提案（毎回同じ言い方にしない）。
- 予定・ToDo・メール・授業が無いものは「無い」と長々言わず、飛ばす。全部無ければ「今日は予定もなくて、ゆっくりできそうです」のように一言。
- 下の授業ノート・ほかの材料に無いことは言わない。

# 最近の授業ノート（復習ポイント）
${lectures}`;
}
